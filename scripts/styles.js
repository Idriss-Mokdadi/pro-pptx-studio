// styles.js — list, search and catalog the style library. MIT License.
//   node styles.js list [--group house|template|system] [--mode dark|light]
//   node styles.js find "5g security"          → best matches for a topic (house + template styles first)
//   node styles.js catalog > ../references/styles.md
const fs = require("fs"), path = require("path");
const DIR = path.join(require("./dataroot.js").dataRoot(), "styles");
const all = () => fs.readdirSync(DIR).filter((f) => f.endsWith(".json")).map((f) => JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8")));
const [cmd, ...rest] = process.argv.slice(2);
const opt = (k) => { const i = rest.indexOf(k); return i >= 0 ? rest[i + 1] : null; };
if (cmd === "list") {
  for (const s of all().filter((s) => (!opt("--group") || s.group === opt("--group")) && (!opt("--mode") || s.mode === opt("--mode"))).sort((a, b) => (b.weight || 0) - (a.weight || 0)))
    console.log(`${s.id.padEnd(20)} ${s.group.padEnd(8)} ${s.mode.padEnd(5)} ${String(s.weight || 0).padStart(3)}  ${s.fonts.display} / ${s.fonts.body}  [${(s.tags || []).join(", ")}]`);
} else if (cmd === "find") {
  const q = rest.join(" ").toLowerCase();
  const r = all().map((s) => ({ s, score: (s.tags || []).filter((t) => q.includes(t)).length * 40 + (s.group === "system" ? 0 : (s.weight || 0) * 0.6) })).sort((a, b) => b.score - a.score).slice(0, 10);
  r.forEach(({ s, score }) => console.log(`${s.id.padEnd(20)} ${Math.round(score).toString().padStart(4)}  ${s.name} — ${s.mode}, ${s.background.recipe} background, ${s.card.kind} cards${s.source ? " (from " + s.source + ")" : ""}`));
} else if (cmd === "catalog") {
  const g = { house: "House styles (built from your board choices and Canva templates)", template: "Imported from your templates", system: "Ported design systems (beautiful-html-templates, MIT)" };
  let out = "# Style catalog\n\nGenerated by `node scripts/styles.js catalog`. `weight` is how much the user liked the look (0–100) and drives automatic picks.\n";
  for (const k of Object.keys(g)) {
    const ss = all().filter((s) => s.group === k).sort((a, b) => (b.weight || 0) - (a.weight || 0)); if (!ss.length) continue;
    out += `\n## ${g[k]}\n\n| id | mode | look | fonts | best for | weight |\n|---|---|---|---|---|---|\n`;
    for (const s of ss) out += `| \`${s.id}\` | ${s.mode} | ${s.background.recipe} background, ${s.card.kind} cards, ${s.hero?.kind || "no"} hero${s.source ? `; from ${s.source}` : ""} | ${s.fonts.display} / ${s.fonts.body} | ${(s.tags || []).join(", ")} | ${s.weight || 0} |\n`;
  }
  process.stdout.write(out);
} else console.log("usage: node styles.js list|find <topic>|catalog");
